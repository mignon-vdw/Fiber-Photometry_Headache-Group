"""
runner.py

Executes the experiment by iterating through a sequence
of Trial objects and instructing the Arduino to deliver
the appropriate stimulus.

Parameters:
trials: list[Trial]
Sequence of trials generated by trial_generator.py.

arduino: Arduino
Active Arduino controller object.
"""

from orexin_photometry.logging.session_logger import SessionLogger

import time 
from datetime import datetime

def run_session(trials, arduino, logger):

    for trial in trials:

        print(
            f"{datetime.now()} | "
            f"Running Trial {trial.trial_number}:"
            f"{trial.stimulus}"
        )

        #Wait for scheduled ITI
        time.sleep(trial.iti_s)

        #Log trial
        logger.log_trial(trial)

        #Deliver the stimulus
        if trial.stimulus == "light":

            arduino.trigger_light()

        elif trial.stimulus == "airpuff":

            arduino.trigger_airpuff()